import { resolve } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';

const base = resolve('demo-iterations/v23/capture');
const videoDir = resolve(base, 'video');
await mkdir(videoDir, { recursive: true });
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
const context = await browser.newContext({
  viewport: { width: 1280, height: 720 },
  recordVideo: { dir: videoDir, size: { width: 1280, height: 720 } },
});
const page = await context.newPage();
page.setDefaultTimeout(12000);
const marks = {};
const start = Date.now();
const mark = (name) => { marks[name] = Number(((Date.now() - start) / 1000).toFixed(3)); };
const beat = async () => page.waitForTimeout(2000);

await page.goto('http://127.0.0.1:3033/', { waitUntil: 'networkidle' });
await beat();
mark('entry');
await page.waitForTimeout(2200);
await page.getByRole('button', { name: 'Start privately' }).click();
await beat();
mark('private-start');
const input = page.getByRole('textbox', { name: 'Your message' });
await input.fill('I want time to decide what I want, but saying that feels ungrateful.');
await beat();
await page.getByRole('button', { name: 'Send', exact: true }).click();
await beat();
mark('opening-entered');
await page.getByRole('button', { name: 'Not quite' }).click();
await beat();
await input.fill('I want time to decide what I want, without someone choosing stay or leave for me.');
await beat();
await page.getByRole('button', { name: 'Send', exact: true }).click();
await page.getByLabel('Updated editable understanding').waitFor();
await beat();
mark('corrected');

await page.getByRole('button', { name: 'Yes, that’s closer' }).click();
await beat();
await page.getByRole('button', { name: 'Keep this takeaway privately' }).click();
await beat();
mark('takeaway-kept-inline');
await page.getByRole('button', { name: 'Hear experiences' }).click();
await beat();
await page.getByRole('button', { name: 'Explore community' }).first().click();
await beat();
mark('community-open');
await page.locator('.story-card').filter({ hasText: 'Ravi' }).getByRole('button', { name: 'Read experience' }).click();
await beat();
const overlap = page.locator('.story-overlap');
const difference = page.locator('.difference-panel');
await difference.scrollIntoViewIfNeeded();
await beat();
mark('match-and-difference');
await page.waitForTimeout(2500);
await page.getByRole('button', { name: 'Ask Ravi in the group' }).click();
await beat();
mark('question-open');
const question = page.getByRole('textbox', { name: 'Your question' });
await question.fill('Could I take time to decide before answering?');
await beat();
const consent = page.getByRole('checkbox', { name: /I reviewed this exact alias/ });
const continueButton = page.getByRole('button', { name: 'Continue to prepared response' });
if (await consent.isChecked()) throw new Error('Consent should remain unchecked');
if (await continueButton.isEnabled()) throw new Error('Continue should remain disabled');
const questionPreview = await page.locator('.recipient-preview dd').nth(2).innerText();
if (questionPreview !== 'Could I take time to decide before answering?') throw new Error(`Preview did not match: ${questionPreview}`);
await page.mouse.wheel(0, 350);
await beat();
for (const locator of [question, page.locator('.recipient-preview'), consent, continueButton]) {
  const box = await locator.boundingBox();
  if (!box || box.y < 0 || box.y + box.height > 720) throw new Error('Question, exact audience preview, consent and disabled action must all be on screen after the scroll');
}
mark('question-edited');
await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name: 'Find Support' }).click();
await beat();
await page.getByRole('button', { name: 'Explore professional support' }).click();
await page.getByRole('heading', { name: /verified provider for these preferences/ }).waitFor();
await beat();
mark('support-limit');
await page.getByRole('button', { name: 'Return to peer perspectives' }).click();
await beat();
await page.getByRole('tab', { name: 'Discussions' }).click();
await beat();
await page.getByRole('button', { name: /Day 16/ }).click();
await beat();
mark('day-16');
await page.getByRole('button', { name: 'Maybe later' }).click();
await beat();
const maybeLater = await page.getByText(/Maybe later selected/).innerText();
if (!maybeLater.includes('private reflection stays private')) throw new Error(`Unexpected deferral state: ${maybeLater}`);
await page.waitForTimeout(1300);
await page.getByRole('button', { name: 'Keep this takeaway privately' }).click();
await beat();
const takeaway = await page.getByRole('status').last().innerText();
if (!takeaway.includes('preview session only')) throw new Error(`Unexpected takeaway state: ${takeaway}`);
mark('private-takeaway-selected');
await page.waitForTimeout(1000);
mark('end');

const video = page.video();
await context.close();
const videoPath = resolve(videoDir, 'v23-full-route.webm');
await video.saveAs(videoPath);
await browser.close();
await writeFile(resolve(base, 'capture-marks.json'), JSON.stringify({ marks, verified: { questionPreview, consentUnchecked: true, continueDisabled: true, maybeLater, takeaway } }, null, 2) + '\n');
console.log(JSON.stringify({ marks, videoPath, verified: { questionPreview, consentUnchecked: true, continueDisabled: true, maybeLater, takeaway } }, null, 2));
