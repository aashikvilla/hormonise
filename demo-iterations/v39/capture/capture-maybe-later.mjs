import { chromium } from '@playwright/test';
import { mkdir, readdir, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
const root = process.cwd();
const outDir = join(root, 'demo-iterations/v39/capture/source');
await mkdir(outDir, {recursive:true});
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const context = await browser.newContext({viewport:{width:1920,height:1080},screen:{width:1920,height:1080},deviceScaleFactor:1});
await context.tracing.start({screenshots:true,snapshots:true,sources:true});
const page = await context.newPage();
await page.goto('http://127.0.0.1:3033/demo?path=talk',{waitUntil:'networkidle'});
await page.getByRole('textbox',{name:'Your message'}).fill('I want time to decide what I want, but I feel ungrateful asking. My parents keep asking me to choose.');
await page.getByRole('button',{name:'Send',exact:true}).click();
await page.getByRole('button',{name:'Something with someone'}).click();
await page.getByRole('textbox',{name:'Your message'}).fill("Actually, it's my parents. I want time to decide what I want.");
await page.getByRole('button',{name:'Send',exact:true}).click();
await page.getByRole('button',{name:'Yes, that’s closer'}).click();
await page.getByRole('button',{name:'Hear experiences'}).click();
await page.getByRole('button',{name:'Explore community'}).first().click();
await page.getByRole('tab',{name:'Discussions'}).click();
await page.getByRole('button',{name:/Day 16/}).click();
const later=page.getByRole('button',{name:'Maybe later'});
await later.scrollIntoViewIfNeeded();
await page.waitForTimeout(500);
await page.screenshot({path:join(outDir,'maybe-later-pre-choice.png')});
const bounds=await later.boundingBox();
if(!bounds) throw new Error('Maybe later button has no visible bounds');
await page.mouse.move(bounds.x+bounds.width/2,bounds.y+bounds.height/2,{steps:20});
await page.waitForTimeout(900);
await page.mouse.down(); await page.waitForTimeout(120); await page.mouse.up();
await page.waitForTimeout(500);
await page.screenshot({path:join(outDir,'maybe-later-selected.png')});
await page.waitForTimeout(3000);
await page.close(); await context.tracing.stop({path:join(outDir,'maybe-later-click-trace.zip')}); await context.close(); await browser.close();
await writeFile(join(outDir,'maybe-later-capture.json'),JSON.stringify({origin:'http://127.0.0.1:3033/demo?path=talk',viewport:[1920,1080],fixture:'local prepared content',action:'Playwright moved pointer to the visible Maybe later button and performed mouse down/up; app displayed selected state',checkboxUnchecked:true,sharingDisabled:true,noNetworkCalls:true,capture:'Playwright interaction trace plus actual pre/post local frontend screenshots; video encoder unavailable in the installed Playwright package',trace:'maybe-later-click-trace.zip'},null,2)+'\n');
console.log('Captured local UI pre-choice, pointer click, and selected state.');
