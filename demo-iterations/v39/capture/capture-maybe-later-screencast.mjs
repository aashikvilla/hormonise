import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
const root=process.cwd(), out=join(root,'demo-iterations/v39/capture/source'), tmp='/tmp/harmonise-v39-maybe-frames';
await mkdir(out,{recursive:true}); await mkdir(tmp,{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1920,height:1080},screen:{width:1920,height:1080},deviceScaleFactor:1});
const page=await context.newPage();
await page.goto('http://127.0.0.1:3033/demo?path=talk',{waitUntil:'networkidle'});
const send=async(text)=>{const box=page.getByRole('textbox',{name:'Your message'});await box.fill(text);await page.getByRole('button',{name:'Send',exact:true}).click();};
await send('I want time to decide what I want, but I feel ungrateful asking. My parents keep asking me to choose.');
await page.getByRole('button',{name:'Something with someone'}).click();
await send("Actually, it's my parents. I want time to decide what I want.");
await page.getByRole('button',{name:'Yes, that’s closer'}).click();
await page.getByRole('button',{name:'Hear experiences'}).click();
await page.getByRole('button',{name:'Explore community'}).first().click();
await page.getByRole('tab',{name:'Discussions'}).click();
await page.getByRole('button',{name:/Day 16/}).click();
const later=page.getByRole('button',{name:'Maybe later'}); await later.scrollIntoViewIfNeeded();
const cdp=await context.newCDPSession(page); let index=0; const meta=[];
cdp.on('Page.screencastFrame',async event=>{
 const n=index++; const path=join(tmp,`frame-${String(n).padStart(6,'0')}.jpg`);
 await writeFile(path,Buffer.from(event.data,'base64'));
 meta.push({frame:n,timestamp:event.metadata?.timestamp ?? null,deviceWidth:event.metadata?.deviceWidth,deviceHeight:event.metadata?.deviceHeight});
 await cdp.send('Page.screencastFrameAck',{sessionId:event.sessionId});
});
await cdp.send('Page.startScreencast',{format:'jpeg',quality:88,everyNthFrame:1,maxWidth:1920,maxHeight:1080});
await page.waitForTimeout(800);
const b=await later.boundingBox(); await page.mouse.move(b.x+b.width/2,b.y+b.height/2,{steps:16});
await page.waitForTimeout(800); await page.mouse.down(); await page.waitForTimeout(120); await page.mouse.up();
await page.waitForTimeout(3000);
await cdp.send('Page.stopScreencast'); await cdp.detach();
await context.close(); await browser.close();
await writeFile(join(out,'maybe-later-screencast-frames.json'),JSON.stringify({frames:meta.length,dimensions:meta[0] ? [meta[0].deviceWidth,meta[0].deviceHeight] : null,framesMetadata:meta},null,2)+'\n');
console.log(`Captured ${meta.length} local Chrome CDP screencast frames to ${tmp}`);
