import { chromium } from '@playwright/test';
import { join } from 'node:path';
const outDir = join(process.cwd(), 'demo-iterations/v39/capture/source');
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const context = await browser.newContext({viewport:{width:768,height:864},screen:{width:768,height:864},deviceScaleFactor:2});
const page = await context.newPage();
await page.goto('http://127.0.0.1:3033/demo?path=talk',{waitUntil:'networkidle'});
await page.getByRole('textbox',{name:'Your message'}).fill('I want time to decide what I want, but I feel ungrateful asking. My parents keep asking me to choose.');
await page.getByRole('button',{name:'Send',exact:true}).click();
await page.getByRole('button',{name:'Something with someone'}).click();
await page.getByRole('textbox',{name:'Your message'}).fill("Actually, it's my parents. I want time to decide what I want.");
await page.getByRole('button',{name:'Send',exact:true}).click();
await page.getByRole('button',{name:'Yes, that’s closer'}).click();
await page.getByRole('button',{name:'Hear experiences'}).click();
await page.getByRole('button',{name:'Explore community'}).first().click();
await page.getByRole('tab',{name:'Discussions'}).click();
await page.getByRole('button',{name:/Day 16/}).click();
await page.getByRole('button',{name:'Offer one thing that helped'}).click();
const preview=page.locator('.dev-bounded-preview');
await preview.waitFor({state:'visible'});
await preview.screenshot({path:join(outDir,'share-preview-panel-768-dpr2.png'),scale:'device'});
await page.getByRole('button',{name:'Maybe later'}).click();
await page.locator('.dev-choice-panel').screenshot({path:join(outDir,'maybe-later-selected-768-dpr2.png'),scale:'device'});
await context.close(); await browser.close();
console.log('Captured 2x device-scale screenshots of the actual local share and selected choice states.');
