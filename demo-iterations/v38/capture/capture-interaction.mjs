import { chromium } from '@playwright/test';
import { mkdir, readdir, rename } from 'node:fs/promises';
import { join } from 'node:path';
const root = process.cwd();
const outDir = join(root, 'demo-iterations/v37/capture/source');
await mkdir(outDir, {recursive:true});
const browser = await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const context = await browser.newContext({viewport:{width:1920,height:1080},screen:{width:1920,height:1080},deviceScaleFactor:1,recordVideo:{dir:outDir,size:{width:1920,height:1080}}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:3033/demo?path=talk',{waitUntil:'networkidle'});
await page.waitForTimeout(400);
await page.screenshot({path:join(outDir,'source-opening.png')});
await page.getByRole('textbox',{name:'Your message'}).fill('I want time to decide what I want, but I feel ungrateful asking. My parents keep asking me to choose.');
await page.waitForTimeout(250);
await page.getByRole('button',{name:'Send',exact:true}).click();
await page.getByRole('button',{name:'Not quite',exact:true}).waitFor({state:'visible'});
await page.waitForTimeout(700);
await page.screenshot({path:join(outDir,'source-proposed-reflection.png'),fullPage:true});
await page.getByRole('button',{name:'Not quite',exact:true}).click();
await page.waitForTimeout(450);
await page.getByRole('button',{name:'Edit in my words',exact:true}).click();
const composer=page.getByRole('textbox',{name:'Your message'});
await composer.click(); await composer.press('Control+A');
await composer.pressSequentially("It's my parents. I want time to decide what I want.",{delay:32});
await page.waitForTimeout(450);
await page.screenshot({path:join(outDir,'source-correction-being-typed.png'),fullPage:true});
await page.getByRole('button',{name:'Send',exact:true}).click();
const reflection=page.getByRole('textbox',{name:'WHAT HE CONFIRMED · EDITABLE'});
await reflection.waitFor({state:'visible'});
await reflection.click(); await reflection.press('Control+A');
await reflection.pressSequentially("It's my parents. I want time to decide what I want.",{delay:32});
await page.waitForTimeout(650);
await page.getByRole('button',{name:'Yes, that’s closer'}).click();
await page.waitForTimeout(1000);
await page.evaluate(()=>window.scrollBy(0,255));
await page.waitForTimeout(350);
await page.screenshot({path:join(outDir,'source-updated-reflection-viewport.png')});
await page.screenshot({path:join(outDir,'source-updated-reflection.png'),fullPage:true});
await page.waitForTimeout(9000);
await page.close(); await context.close(); await browser.close();
const videos=(await readdir(outDir)).filter(x=>x.endsWith('.webm'));
if(videos.length!==1) throw new Error(`Expected one webm, got ${videos}`);
await rename(join(outDir,videos[0]),join(outDir,'continuous-correction-raw.webm'));
console.log(`Wrote ${join(outDir,'continuous-correction-raw.webm')}`);
